/** Describes a number of sixteenths in words, e.g. 6 → "dörtlük + sekizlik". */
export function describeUnits(units: number, s: Strings): string {
  const parts: string[] = [];
  let left = units;
  for (const size of [16, 8, 4, 2, 1]) {
    if (left >= size) {
      parts.push(s.units[16 / size]);
      left -= size;
    }
  }
  return parts.join(' + ');
}
